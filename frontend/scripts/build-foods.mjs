function slugify(s) {
  return s
    .toLowerCase()
    .replace(/\(|\)/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function highlight(cal, protein, carbs, fat, fiber) {
  const tags = [];
  if (protein >= 20) tags.push("high-protein");
  if (cal <= 50) tags.push("low-calorie");
  if (fat <= 1 && cal < 150) tags.push("low-fat");
  if (fiber >= 5) tags.push("high-fiber");
  if (carbs <= 5 && cal < 150) tags.push("low-carb");
  if (cal >= 400) tags.push("calorie-dense");
  return tags;
}

const foods = raw.map(([name, category, prep, cal, protein, carbs, fat, fiber, sugar, sodium], i) => {
  const slug = slugify(name);
  const icon = foodIconOverrides[name] || categoryDefaultIcons[category] || "🍽️";
  return {
    id: i + 1,
    slug,
    name,
    category,
    icon,
    preparation: prep,
    servingSizeG: 100,
    calories: cal,
    protein_g: protein,
    carbs_g: carbs,
    fat_g: fat,
    fiber_g: fiber,
    sugar_g: sugar,
    sodium_mg: sodium,
    tags: highlight(cal, protein, carbs, fat, fiber),
  };
});

